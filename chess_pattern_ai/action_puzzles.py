#!/usr/bin/env python3
"""
Puzzles whose moves the player must learn (Lights Out, Sokoban)

An environment shows a grid of integers and a list of actions; each action
gives the next grid and whether the goal is reached. The goal is told to
the player as "no cell holds a value in GOAL_ABSENT"; what the actions do
is not.

- Lights Out (n x n): cells 0 (off) / 1 (on); an action presses a cell
  (r, c). Pressing toggles a fixed pattern around the cell: the cell and
  its 4 neighbours (standard), or its 3x3 block (variant). Goal: no light
  on. Generated by random presses from the all-off grid, so solvable.
- Sokoban: 0 floor, 1 wall, 2 target, 3 box, 4 box on target, 5 player,
  6 player on target; actions 'N', 'S', 'W', 'E'. The player moves one
  cell; a box in the way is pushed if the cell beyond it is free. Goal: no
  box off a target. Generated by pulling boxes away from their targets,
  so solvable, keeping levels whose shortest solution (breadth-first
  search) takes at least min_moves moves.
"""

import random
from collections import deque
from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np

Pos = Tuple[int, int]
DIRS = {'N': (-1, 0), 'S': (1, 0), 'W': (0, -1), 'E': (0, 1)}


class Environment:
    goal_absent: Tuple[int, ...] = ()

    def __init__(self, grid: np.ndarray, step_limit: int):
        self.grid = grid.copy()
        self.steps = 0
        self.step_limit = step_limit

    def observation(self) -> np.ndarray:
        return self.grid.copy()

    def won(self) -> bool:
        return not np.isin(self.grid, self.goal_absent).any()

    def is_over(self) -> bool:
        return self.won() or self.steps >= self.step_limit

    def actions(self) -> List:
        raise NotImplementedError

    def step(self, action) -> Tuple[np.ndarray, bool]:
        self.grid = self.apply(self.grid, action)
        self.steps += 1
        return self.observation(), self.won()

    def apply(self, grid: np.ndarray, action) -> np.ndarray:
        raise NotImplementedError


# ------------------------------------------------------------ Lights Out

class LightsOut(Environment):
    goal_absent = (1,)

    def __init__(self, grid, pattern: Sequence[Pos], step_limit: int = 100):
        super().__init__(grid, step_limit)
        self.pattern = list(pattern)

    def actions(self):
        n, m = self.grid.shape
        return [(r, c) for r in range(n) for c in range(m)]

    def apply(self, grid, action):
        out = grid.copy()
        r, c = action
        for dr, dc in self.pattern:
            if 0 <= r + dr < grid.shape[0] and 0 <= c + dc < grid.shape[1]:
                out[r + dr, c + dc] ^= 1
        return out


PLUS = [(0, 0), (-1, 0), (1, 0), (0, -1), (0, 1)]
BLOCK = [(dr, dc) for dr in (-1, 0, 1) for dc in (-1, 0, 1)]


def solve_xor(masks: np.ndarray, target: np.ndarray) -> Optional[np.ndarray]:
    """
    Fewest presses x (0/1 per action) with masks.T @ x = target (mod 2);
    masks is actions x cells. None if impossible.
    """
    a = np.concatenate([masks.T % 2, target.reshape(-1, 1) % 2], axis=1).astype(np.uint8)
    rows, cols = a.shape[0], masks.shape[0]
    pivots, r = [], 0
    for c in range(cols):
        hit = next((i for i in range(r, rows) if a[i, c]), None)
        if hit is None:
            continue
        a[[r, hit]] = a[[hit, r]]
        for i in range(rows):
            if i != r and a[i, c]:
                a[i] ^= a[r]
        pivots.append(c)
        r += 1
    if any(a[i, -1] for i in range(r, rows)):
        return None
    free = [c for c in range(cols) if c not in pivots]
    best = None
    for bits in range(2 ** min(len(free), 12)):
        x = np.zeros(cols, dtype=np.uint8)
        for k, c in enumerate(free[:12]):
            x[c] = (bits >> k) & 1
        for i, c in enumerate(pivots):
            x[c] = (a[i, -1] + sum(int(a[i, f]) * int(x[f]) for f in free)) % 2
        if best is None or x.sum() < best.sum():
            best = x
    return best


def lights_out(seed: int, n: int = 5, pattern=PLUS) -> LightsOut:
    rng = np.random.default_rng(seed)
    env = LightsOut(np.zeros((n, n), dtype=int), pattern)
    while not env.grid.any():
        for a in env.actions():
            if rng.random() < 0.5:
                env.grid = env.apply(env.grid, a)
    env.optimal = int(solve_xor(_masks(env), env.grid.ravel()).sum())
    return env


def _masks(env: LightsOut) -> np.ndarray:
    zero = np.zeros_like(env.grid)
    return np.array([env.apply(zero, a).ravel() for a in env.actions()])


# --------------------------------------------------------------- Sokoban

FLOOR, WALL, TARGET, BOX, BOX_ON_TARGET, PLAYER, PLAYER_ON_TARGET = range(7)


class Sokoban(Environment):
    goal_absent = (BOX,)

    def __init__(self, grid, step_limit: int = 200):
        super().__init__(grid, step_limit)

    def actions(self):
        return list(DIRS)

    def apply(self, grid, action):
        out = grid.copy()
        (pr, pc), = zip(*np.nonzero(np.isin(grid, (PLAYER, PLAYER_ON_TARGET))))
        dr, dc = DIRS[action]
        a, b = (pr + dr, pc + dc), (pr + 2 * dr, pc + 2 * dc)

        def inside(p):
            return 0 <= p[0] < grid.shape[0] and 0 <= p[1] < grid.shape[1]
        if not inside(a) or grid[a] == WALL:
            return out
        if grid[a] in (BOX, BOX_ON_TARGET):
            if not inside(b) or grid[b] not in (FLOOR, TARGET):
                return out
            out[b] = BOX_ON_TARGET if grid[b] == TARGET else BOX
        out[a] = PLAYER_ON_TARGET if grid[a] in (TARGET, BOX_ON_TARGET) else PLAYER
        out[pr, pc] = TARGET if grid[pr, pc] == PLAYER_ON_TARGET else FLOOR
        return out


def shortest(env: Environment, start: np.ndarray, limit: int = 200_000) -> Optional[int]:
    """Length of the shortest solution with the true rules (None if none within the limit)"""
    seen = {start.tobytes()}
    queue = deque([(start, 0)])
    while queue and len(seen) < limit:
        g, d = queue.popleft()
        if not np.isin(g, env.goal_absent).any():
            return d
        for a in env.actions():
            h = env.apply(g, a)
            k = h.tobytes()
            if k not in seen:
                seen.add(k)
                queue.append((h, d + 1))
    return None


def sokoban(seed: int, size: int = 7, boxes: int = 2, pulls: int = 80, min_moves: int = 8) -> Sokoban:
    rng = random.Random(seed)
    while True:
        g = np.full((size, size), WALL, dtype=int)
        g[1:-1, 1:-1] = FLOOR
        inner = [(r, c) for r in range(1, size - 1) for c in range(1, size - 1)]
        for p in rng.sample(inner, rng.randint(0, 3)):
            g[p] = WALL
        free = [p for p in inner if g[p] == FLOOR]
        cells = rng.sample(free, boxes + 1)
        for p in cells[:boxes]:
            g[p] = BOX_ON_TARGET
        g[cells[boxes]] = PLAYER
        # pull boxes away from the targets with reversed moves
        for _ in range(pulls):
            (pr, pc), = zip(*np.nonzero(np.isin(g, (PLAYER, PLAYER_ON_TARGET))))
            d = rng.choice(list(DIRS))
            dr, dc = DIRS[d]
            to, box = (pr - dr, pc - dc), (pr + dr, pc + dc)
            if g[to] not in (FLOOR, TARGET):
                continue
            pull = g[box] in (BOX, BOX_ON_TARGET) and rng.random() < 0.7
            if pull:
                g[(pr, pc)] = BOX_ON_TARGET if g[(pr, pc)] == PLAYER_ON_TARGET else BOX
                g[box] = TARGET if g[box] == BOX_ON_TARGET else FLOOR
            else:
                g[(pr, pc)] = TARGET if g[(pr, pc)] == PLAYER_ON_TARGET else FLOOR
            g[to] = PLAYER_ON_TARGET if g[to] == TARGET else PLAYER
        env = Sokoban(g)
        if env.won():
            continue
        best = shortest(env, g)
        if best is not None and best >= min_moves:
            env.optimal = best
            return env


ENVIRONMENTS = {
    'lights out 5x5': lambda seed: lights_out(seed),
    'lights out 5x5 (3x3 toggles)': lambda seed: lights_out(seed, pattern=BLOCK),
    'sokoban 7x7, 2 boxes': lambda seed: sokoban(seed),
    'sokoban 8x8, 3 boxes': lambda seed: sokoban(seed, size=8, boxes=3, pulls=120, min_moves=12),
}
